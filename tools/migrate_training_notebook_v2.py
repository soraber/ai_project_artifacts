def main():
    notebook = json.loads(PATH.read_text())
    cells = {c.get('id'): ''.join(c['source']) for c in notebook['cells']}
    if hashlib.sha256(cells['253ca33c'].encode()).hexdigest() != PROTECTED:
        raise RuntimeError('Protected dataset source changed; review before proceeding')
    updates = replacements(cells)
    baseline = json.loads(subprocess.check_output(['git', 'show', f'HEAD:{PATH.name}'], cwd=ROOT))
    original = {c.get('id'): ''.join(c['source']) for c in baseline['cells']}
    for identifier, value in updates.items():
        if cells[identifier] not in (value, original[identifier]):
            raise RuntimeError(f'Preserving locally edited cell {identifier}; merge explicitly')
    changed = []
    for index, cell in enumerate(notebook['cells'], 1):
        if cell.get('id') in updates and ''.join(cell['source']) != updates[cell['id']]:
            cell['source'] = updates[cell['id']].splitlines(keepends=True)
            if cell['cell_type'] == 'code':
                cell.update(outputs=[], execution_count=None)
            changed.append({'cell': index, 'id': cell['id']})
    PATH.write_text(json.dumps(notebook, indent=1)+'\n')
    print(json.dumps(changed))


